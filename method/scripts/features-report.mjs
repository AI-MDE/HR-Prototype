// The Features report (docs/features-report.md): every build Feature by its primary Target (the
// first it impacts), with a one-line abstract, the other Targets it impacts, and its number of
// script Checks; then the optional Features. Generated from method/features/ and the optional
// Feature catalog, never written by hand, so it cannot drift from them. Run by
// compile-targets.mjs, and only where the Method sits beside MDE's own docs/ (MDE's repository,
// not an application's copy of the Method).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const methodDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const docsDir = path.resolve(methodDir, '..', 'docs');
const NONE = 'None (never compiled into a Target)';
const ORDER = ['business-requirements', 'architecture', 'application-design', 'api-design', 'ui-design', 'persistence-design', 'prototype',
  'dev-setup', 'run-app', 'server', 'api', 'persistence', 'integration', 'web-ui', 'testing', 'evidence', 'documentation', 'deployment', 'method-change', NONE];

const read = (f) => fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n');
function frontMatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  const out = {};
  let key = null;
  for (const line of m ? m[1].split('\n') : []) {
    const top = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
    if (top) {
      key = top[1];
      const v = top[2].trim();
      out[key] = v.startsWith('[') ? v.slice(1, -1).split(',').map((x) => x.trim()).filter(Boolean) : v || [];
      continue;
    }
    const item = line.match(/^\s+-\s+(.*)$/);
    if (item && key) { if (!Array.isArray(out[key])) out[key] = []; out[key].push(item[1].trim()); }
  }
  return out;
}
const clean = (s) => {
  s = s.replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').replace(/\*\*/g, '').split(/\s+/).join(' ').trim();
  return s.length <= 220 ? s : `${s.slice(0, 217).replace(/\s+\S*$/, '')}…`;
};
const sentences = (p) => p.split(/(?<=[.!?])\s+(?=[A-Z`*[])/);
// The Feature's first sentence of Purpose; a Purpose that only says "the rules of the X Target"
// gives way to the first sentence of its first Impact section.
function abstract(text) {
  const body = text.replace(/^---\n[\s\S]*?\n---\n/, '');
  const purpose = body.match(/^## Purpose\s*\n+([\s\S]+?)(?:\n\n|\n## |$)/m)?.[1].split(/\s+/).join(' ') || '';
  const ss = purpose ? sentences(purpose) : [''];
  let s = ss[0];
  if (!s.trim() || /rules of the .* Target that no other Feature supplies/.test(s)) {
    const impact = body.match(/^## Impact on [^\n]*\n+([\s\S]+?)(?:\n\n|\n## |$)/m)?.[1];
    if (impact) {
      const first = impact.trim().split('\n- ')[0].replace(/^\s*[-*]\s+/, '').split(/\s+/).join(' ').replace(/^\*\*[^*]+\*\*:?\s*/, '');
      s = sentences(first)[0];
    }
  } else if (s.length < 50 && ss.length > 1) s = `${s} ${ss[1]}`;
  return clean(s);
}
function walk(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(p));
    else if (e.name.endsWith('.md') && e.name !== 'README.md' && e.name !== 'index.md') out.push(p);
  }
  return out.sort();
}

export function featuresReport() {
  const rows = [];
  for (const file of walk(path.join(methodDir, 'features'))) {
    const text = read(file), fm = frontMatter(text);
    if (fm.type !== 'feature') continue;
    const impacts = Array.isArray(fm.impacts) ? fm.impacts : fm.impacts ? [fm.impacts] : [];
    const verify = text.includes('\n## Verify\n') ? text.split('\n## Verify\n')[1].split('\n## ')[0] : '';
    rows.push({
      target: impacts[0] || NONE, id: fm.id || path.basename(file, '.md'), abstract: abstract(text),
      also: impacts.slice(1).join(', '), checks: (verify.match(/^- `[a-z0-9-]+` /gm) || []).length,
      rel: path.relative(methodDir, file).split(path.sep).join('/'),
    });
  }
  let optional = [];
  try {
    const cat = JSON.parse(read(path.join(methodDir, 'optional-features', 'catalog.json')));
    optional = Array.isArray(cat) ? cat : Array.isArray(cat.features) ? cat.features : Object.entries(cat.features || {}).map(([id, f]) => ({ id, ...f }));
  } catch { /* no catalog */ }
  const by = new Map();
  for (const r of rows) by.set(r.target, [...(by.get(r.target) || []), r]);
  const version = read(path.join(methodDir, 'VERSION.md')).trim().split(/\s+/).pop();
  const targets = [...ORDER.filter((t) => by.has(t)), ...[...by.keys()].filter((t) => !ORDER.includes(t)).sort()];
  const cell = (s) => String(s).replace(/\|/g, '/');
  const lines = [
    '# MDE Method — Features', '',
    `<!-- Generated by method/scripts/features-report.mjs (run by compile-targets.mjs). Do not edit: change the Features and recompile. -->`, '',
    `Method ${version}: **${rows.length} build Features**, by primary Target (the first Target each impacts), with a one-line abstract, the other Targets it impacts, and its number of script Checks (*Verify*); then the **${optional.length} optional Features**.`, '',
    '| Primary Target | Build Features |', '|---|---|', ...targets.map((t) => `| ${t} | ${by.get(t).length} |`), '',
  ];
  for (const t of targets) {
    const list = by.get(t).sort((a, b) => a.id.localeCompare(b.id));
    lines.push(`## ${t} (${list.length})`, '');
    if (t === NONE) lines.push('These Features have an empty `impacts:` list: no Target compiles them, so no agent reads them.', '');
    lines.push('| Feature | Abstract | Also impacts | Checks |', '|---|---|---|---|',
      ...list.map((r) => `| [${r.id}](../method/${r.rel}) | ${cell(r.abstract)} | ${r.also || '—'} | ${r.checks || '—'} |`), '');
  }
  lines.push(`## Optional Features (${optional.length})`, '', 'Applied by choice to an object (an entity, an operation, the application), where each says; never compiled into a Target.', '',
    '| Feature | Abstract | Scope | Applied in |', '|---|---|---|---|',
    ...optional.sort((a, b) => String(a.id).localeCompare(String(b.id))).map((o) => {
      const list = (v) => (Array.isArray(v) ? v : v ? [v] : []);
      const link = o.path ? `[${o.id}](../method/optional-features/${o.path})` : o.id;
      return `| ${link} | ${cell(clean(String(o.description || '')))} | ${list(o.scope).join(', ') || '—'} | ${list(o.appliedIn).join(', ') || '—'} |`;
    }), '');
  return { text: lines.join('\n'), features: rows.length, optional: optional.length, uncompiled: (by.get(NONE) || []).length };
}

if (fs.existsSync(docsDir)) {
  const r = featuresReport();
  fs.writeFileSync(path.join(docsDir, 'features-report.md'), r.text, 'utf8');
  console.log(`-> ${path.join(docsDir, 'features-report.md')} (${r.features} build Features, ${r.optional} optional, ${r.uncompiled} never compiled)`);
}
